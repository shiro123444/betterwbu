import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const components=await readFile(path.join(root,'src/components.css'),'utf8');
await writeFile(path.join(root,'extension/components.css'),components);
const managerTheme=await readFile(path.join(root,'src/manager.css'),'utf8')+'\n'+components;
await writeFile(path.join(root,'extension/manager-theme.js'),'// Generated from src/manager.css; do not edit this file.\nwindow.ReimbursementSidebarTheme='+JSON.stringify(managerTheme)+';\n');
await build({entryPoints:[path.join(root,'src/workspace.jsx')],outfile:path.join(root,'extension/workspace.js'),bundle:true,minify:true,
  platform:'browser',format:'iife',target:['chrome111'],jsx:'automatic',define:{'process.env.NODE_ENV':'"production"'},legalComments:'linked'});
for(const [source,target]of [['memory-core.js','memory-core-isolated.js'],['basic-core.js','basic-core-http-isolated.js']])
  await writeFile(path.join(root,'extension',target),await readFile(path.join(root,'extension',source)));
console.log('React workspace built; isolated cores synchronized.');
